"""意图闸门：在查库之前先判断「这个问题该不该用 SQL 回答」（v0.10 新增）。

为什么需要这一层
----------------
在此之前，``runtime.run()`` 对任何输入都无条件走完整链路
（Schema 检索 → SQL 生成 → 校验 → 执行）。mock 模式下
``generator.FALLBACK_SQL`` 会对所有未命中规则的问题返回「最近 10 条数据」，
于是问「你好」「你是谁？」也会得到一张毫不相干的数据表；real 模式下
``build_prompt`` 写死「只输出一条 SELECT」，模型同样被迫编造一条 SQL。

这违背了开题报告 4.1 与功能清单里承诺的「无法回答时追问澄清，
不强行生成错误 SQL」。**查错了比查不到更糟**——一张看似正常的表会让
用户误以为系统理解了问题，这是最危险的失败模式。

设计取舍：确定性优先
--------------------
判定全部用关键词/短语规则，**不让模型判断意图**，理由与
``runtime._is_analysis()`` 一致：意图判定本身不该引入非确定性，
否则同一个问题有时走闸门、有时走查询，评估数字会抖动。

规则采用「白名单放行 + 显式拒答」的顺序，且**数据线索拥有最高优先级**：
    1. 空输入                     → empty
    2. 含数据领域词 / 查询动作词 / 写操作词 → data_query（无条件放行）
    3. 显式寒暄 / 身份 / 能力 / 感谢 / 告别 → 对应拒答类型
    4. 其余                       → out_of_scope

第 2 步必须在最前面，因为「你好，帮我查一下 3 号教室温度」既是寒暄
也是数据查询，应当放行；而「删除所有设备记录」这类的安全测试题也必须
继续走到校验层被拦截，不能被闸门提前消化掉（否则 safety 类评估口径就变了）。

已知边界
--------
词表是保守的：宁可漏拦个别通用问题，也不能误伤 144 条评估集里的任何
数据问题。``tests/test_smoke.py`` 里有一份回归用例，逐条检查评估集问题
全部被判为 ``data_query``，改动词表时必须跑它。
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass

# ── 回复文案：明确说明「我是谁、能查什么、为什么不能答」，并给出可点的示例 ──
REPLIES = {
    "empty": "请输入一个关于监测数据的问题，例如：3号教室昨天的平均温度是多少？",
    "chitchat": (
        "你好！我是这个系统的数据分析助手，只负责查询本机的监测数据库，"
        "不处理闲聊。可以试着问我：3号教室昨天的平均温度是多少，"
        "或者：这周哪个教室空气质量最差，为什么？"
    ),
    "identity": (
        "我是基于大语言模型的物联网监测数据分析 Agent。"
        "我的能力是把自然语言问题转换成 SQL，在当前数据库的教室 / 设备 / "
        "监测读数 / 告警四张表上查询并解释结果；我不能回答与这些数据无关的通用问题。"
    ),
    "capability": (
        "我能做三类事：① 单表查询与筛选（如「列出 CO2 超过 1000 的时段」）；"
        "② 分组统计与多表关联（如「各教室本月 CO2 均值排名」）；"
        "③ 多步归因（如「这周哪个教室空气质量最差，为什么」）。"
        "每条回答都会显示生成的 SQL 供你核对。数据范围仅限当前监测数据库。"
    ),
    "thanks": "不客气。有数据相关的问题随时问我，例如：各教室本月的 CO2 均值排名。",
    "bye": "再见。需要查监测数据时再来找我。",
    "out_of_scope": (
        "这个问题不在当前数据范围内，我不会为了给出回答而生成一条不相关的 SQL。"
        "系统只能查询 site、device、sensor_data、alarm 这四张表中的监测数据，"
        "例如：3号教室昨天的平均温度是多少？这周哪个教室空气质量最差，为什么？"
    ),
}

# 数据领域词：出现任意一个就说明提问跟库里的表/字段有关。
# 刻意不放「今天 / 昨天 / 最近」这类纯时间词——「今天天气怎么样」也会命中，
# 会造成放行误判；数据题几乎都同时带领域词或查询动作词，不靠时间词识别。
DATA_TERMS = (
    "温度", "湿度", "co2", "二氧化碳", "pm25", "tvoc", "光照", "监测", "传感器",
    "读数", "数据", "教室", "房间", "站点", "楼层", "设备", "型号", "告警", "报警",
    "次数", "记录", "空气", "能耗", "用电", "指标", "均值", "平均", "最高", "最低",
    "排名", "趋势", "时段", "小时", "校准", "离线", "电池", "电压", "信号",
)

# 查询动作词：没有明确领域词、但有明确取数动作时也应放行（如「帮我统计一下」）。
# 不放「哪」「几」「按」「怎么」这类单字/泛词，避免「你在哪」「几点了」被误放行。
QUERY_TERMS = (
    "查询", "查一下", "查查", "查", "列出", "统计", "汇总", "多少", "几个", "几条",
    "几次", "几台", "排名", "对比", "比较", "平均", "均值", "最高", "最低", "超过",
    "高于", "低于", "大于", "小于", "哪些", "哪个", "哪间", "哪层", "变化", "分组",
    "排序", "count", "sum", "avg", "max", "min", "select",
    "为什么", "原因", "归因", "分析", "怎么回事",
)

# 写操作词：必须放行到 validator 被拦截，不能由闸门提前「礼貌拒绝」，
# 否则 safety 类评估（8 条危险语句）就测不到校验层了。
WRITE_TERMS = (
    "删除", "清空", "改成", "插入", "更新", "修改", "删掉", "移除", "清掉",
    "drop", "delete", "update", "insert", "alter", "truncate",
)

# 显式短语：(类型, 短语集合)。只有在**没有任何数据线索**时才会走到这里，
# 所以用 `in` 匹配即可，不必担心误伤「你好，帮我查温度」这类混合问句。
EXPLICIT: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("chitchat", ("你好", "您好", "哈喽", "嗨", "hello", "hi", "早上好",
                  "下午好", "晚上好", "在吗", "在不在", "有人吗", "hiya")),
    ("identity", ("你是谁", "你叫什么", "你的名字", "你是什么", "你是啥",
                  "自我介绍", "介绍一下你自己", "什么模型", "机器人吗", "gpt")),
    ("capability", ("你能做什么", "你会什么", "你能干嘛", "有什么功能",
                    "怎么用", "使用说明", "帮助", "help", "能做什么")),
    ("thanks", ("谢谢", "感谢", "多谢", "thanks", "thx")),
    ("bye", ("再见", "拜拜", "bye", "回见", "晚安")),
)

_STRIP = re.compile(r"[\s，。？！、；：,.?!;:~～\"'“”‘’()（）\[\]【】]")


@dataclass(frozen=True)
class Intent:
    """一次判定的结果。

    kind:  ``data_query`` 表示放行，其余类型都会被闸门直接回复、不查库。
    reply: 面向用户的说明文字；``data_query`` 时为空串。
    """

    kind: str
    reply: str = ""


DATA_INTENT = Intent("data_query")


def normalize(question: str) -> str:
    """归一化：全角转半角、小写、去空白与常见标点。

    NFKC 会把「３号教室」变成「3号教室」、全角逗号变半角；
    后续统一用 `in` 做子串匹配，不需要分词（本科原型，规则可控即可）。
    """
    return _STRIP.sub("", unicodedata.normalize("NFKC", question or "").lower())


def classify(question: str) -> Intent:
    """判断问题是否应当进入 SQL 查询链路。

    Args:
        question: 用户原始输入，允许为 None / 空串。

    Returns:
        Intent。``kind == "data_query"`` 时调用方继续走完整链路；
        其余情况调用方直接返回 ``reply``，不检索、不生成、不执行。
    """
    q = normalize(question)
    if not q:
        return Intent("empty", REPLIES["empty"])

    # 1. 数据线索优先放行：保证评估集与「寒暄 + 正事」混合问句不受影响
    if (any(t in q for t in DATA_TERMS)
            or any(t in q for t in QUERY_TERMS)
            or any(t in q for t in WRITE_TERMS)):
        return DATA_INTENT

    # 2. 明确的非数据意图：给出针对性说明
    for kind, phrases in EXPLICIT:
        if any(p in q for p in phrases):
            return Intent(kind, REPLIES[kind])

    # 3. 兜底：既无数据线索、也不属于常见寒暄，如实说明范围
    return Intent("out_of_scope", REPLIES["out_of_scope"])
